    end
    local gap = previousAt ~= nil and self.now - previousAt > self.options.maxGapSeconds
    if gap then
        local duration = self.now - previousAt
        self.quality.gapCount, self.quality.totalGapSeconds = self.quality.gapCount + 1, self.quality.totalGapSeconds + duration
        bounded(self.gaps, {from = previousAt, to = self.now, seconds = duration, life = self.life, reason = "sampling_gap"}, self.options.maxEvents)
        self:_event("sampling_gap", {seconds = duration})
        self.streams.corroborated.pending = nil
        self.streams.corroborated.last = nil
    end
    self:_movement(s, previous, gap)
    self:_updateStream("character", s.charMarks, previousAt, gap)
    self:_updateStream("player", s.playerMarks, previousAt, gap)
    self:_updateAgreement(previousAt, gap)
    self.previous = {t = self.now, life = self.life, present = present,
        x = finite(s.x) and s.x or nil, z = finite(s.z) and s.z or nil,
        eligible = self.current.eligibleByArchivedThreshold, mode = localMode(s)}
    if not self.nextSnapshot or self.now >= self.nextSnapshot then
        local old = bounded(self.snapshots, {at = self.now, life = self.life,
            charMarks = self.current.charMarks, playerMarks = self.current.playerMarks,
            species = self.current.species, growth = self.current.growth,
            movement = copy(self.movement), totals = copy(self.totals)}, self.options.maxSnapshots)
        if old then self.quality.snapshotRecordsDropped = self.quality.snapshotRecordsDropped + 1 end
        self.nextSnapshot = self.now + 60
    end
    return true
end

function Core:_window(seconds)
