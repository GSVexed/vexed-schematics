    local result = {windowSeconds = seconds, intervalStart = now - seconds, intervalEnd = now, sources = {}}
    for _, name in ipairs(SOURCES) do
        local s, total, ambiguous = self.streams[name], 0, 0
        local uncertainBoundary = false
        for _, e in ipairs(self.awards) do
            if e.valid and e.source == name and e.life == self.life and e.intervalEnd > now - seconds and e.intervalEnd <= now then
                if e.intervalStart < now - seconds then
                    uncertainBoundary, ambiguous = true, ambiguous + e.delta
                else
                    total = total + e.delta
                end
            end
        end
        local breakAt = math.max(s.coverageBreak or now, self.startedAt or now, self.overflowAt or -math.huge)
        local coverage = s.ready and math.min(seconds, math.max(0, now - breakAt)) or 0
        local agreementUsable = name ~= "corroborated" or self.current.agreement == "AGREE"
        local pendingDelta = s.pending and s.pending.delta or 0
