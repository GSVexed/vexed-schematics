local function localMode(s)
    if s.swimming == true then
        if s.sprinting == true then return "swim_sprint" end
        if s.sprinting == false then return "swim" end
        return "swim_unknown"
    elseif s.swimming == false then
        if s.sprinting == true then return "sprint" end
        if s.sprinting == false then return "walk" end
        return "land_unknown"
    end
    return "unknown"
end

function Core:_movement(s, previous, gap)
    if not previous then return end
    local dt = self.now - previous.t
    if dt <= 0 then return end
    local m = self.movement
    if gap then
        m.gapSeconds = m.gapSeconds + dt
        return
    end
    if self.life ~= previous.life or not self.current.present or not previous.present
        or not finite(s.x) or not finite(s.z) or not finite(previous.x) or not finite(previous.z) then
        m.missingSeconds = m.missingSeconds + dt
        return
    end
    local dx, dz = s.x - previous.x, s.z - previous.z
    local distance = math.sqrt(dx * dx + dz * dz)
    if not finite(distance) or distance / dt > self.options.maxObservedSpeed then
        m.outlierCount, m.outlierSeconds = m.outlierCount + 1, m.outlierSeconds + dt
        self:_event("displacement_excluded", {seconds = dt, reason = "observer_outlier_filter_not_game_rule"})
        return
    end
    local mode = localMode(s)
    if distance / dt <= self.options.stationarySpeed then
        mode = "stationary"
    elseif mode ~= previous.mode then
        mode = "transition"
    end
    local bucket = m.modes[mode]
    m.seconds, m.distance = m.seconds + dt, m.distance + distance
    bucket.seconds, bucket.distance = bucket.seconds + dt, bucket.distance + distance
    if self.current.eligibleByArchivedThreshold == true and previous.eligible == true then
        m.eligibleSeconds, m.eligibleDistance = m.eligibleSeconds + dt, m.eligibleDistance + distance
        bucket.eligibleSeconds, bucket.eligibleDistance = bucket.eligibleSeconds + dt, bucket.eligibleDistance + distance
    end
end

function Core:step(s)
