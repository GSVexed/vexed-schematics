    local previous, previousAt = self.previous, self.now
    self.now, self.startedAt = s.t, self.startedAt or s.t
    self.quality.samples = self.quality.samples + 1
    local life = finite(s.life) and math.max(0, math.floor(s.life)) or 0
    local present = s.present == true and life > 0
    if life ~= self.life then
        self.life = life
        self.streams = {character = stream(), player = stream(), corroborated = stream()}
        self.evictedCurrentLife = {character={delta=0}, player={delta=0}, corroborated={delta=0}}
        self.quality.observationEpochs = self.quality.observationEpochs + 1
        self:_event("life_changed", {})
    end
    self.current = {life = life, present = present,
        species = s.species == "Hippo" and "Hippo" or (type(s.species) == "string" and "other" or "unknown"),
        growth = finite(s.growth) and s.growth or nil,
        charMarks = mark(s.charMarks) and s.charMarks or nil,
        playerMarks = mark(s.playerMarks) and s.playerMarks or nil,
        agreement = "UNAVAILABLE"}
    if type(s.alive) == "boolean" then self.current.alive = s.alive end
    if self.versionMatches and present and self.current.species == "Hippo" and finite(s.growth) and type(s.alive) == "boolean" then
        -- Native v2411 menu uses ELDER_MAX (2) minus 0.0001 for its tier bar.
