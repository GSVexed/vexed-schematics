local Storage = (function()
-- Injectable, failure-contained local report writer. No network or upload path.
local Storage = {}
Storage.__index = Storage
local function clone(t)
    if type(t) ~= "table" then return t end
    local r = {}
    for k, v in pairs(t) do r[k] = clone(v) end
    return r
end
function Storage.new(options)
    options = options or {}
    return setmetatable({encode = options.encode, write = options.write, filename = options.filename,
        state = {available = type(options.write) == "function", attempts = 0, successfulWrites = 0,
            failures = 0, lastStatus = "NOT_ATTEMPTED", uploaded = false}}, Storage)
end
function Storage:status()
    return clone(self.state)
end
function Storage:flush(report, at)
    self.state.attempts = self.state.attempts + 1
    if not self.state.available then
        self.state.lastStatus = "NO_LOCAL_WRITEFILE"
        return false, self.state.lastStatus
    end
    local data = clone(report)
    data.storage = self:status()
    data.storage.snapshotBeforeWrite = true
    local ok, text = pcall(self.encode, data)
    if not ok or type(text) ~= "string" then
        self.state.failures = self.state.failures + 1
        self.state.lastStatus = "JSON_ENCODING_FAILED"
        return false, self.state.lastStatus
    end
    local written = pcall(self.write, self.filename, text)
    if not written then
        self.state.failures = self.state.failures + 1
        self.state.lastStatus = "LOCAL_WRITE_FAILED"
        return false, self.state.lastStatus
    end
    self.state.successfulWrites = self.state.successfulWrites + 1
    self.state.lastSuccessfulAt = at
    self.state.lastStatus = "LOCAL_WRITE_SUCCEEDED"
    return true
end
return Storage

end)()
