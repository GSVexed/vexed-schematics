function Core:_updateAgreement(previousAt, forceBaseline)
    local a, b, s = self.streams.character, self.streams.player, self.streams.corroborated
    if not a.ready or not b.ready or not a.present or not b.present then
        s.pending, s.ready, s.coverageBreak, s.last = nil, false, self.now, nil
        self.current.agreement = "UNAVAILABLE"
        return
    end
    if not s.ready then
        s.ready, s.coverageBreak = true, self.now
    end
    if math.abs(a.last - b.last) > self.options.progressEpsilon then
        self.current.agreement = "DISAGREE"
        -- A short replication delay does not erase the previously agreed baseline.
        s.disagreementSince = s.disagreementSince or self.now
        if self.now - s.disagreementSince > self.options.maxReplicationLagSeconds then
            s.coverageBreak, s.last, s.pending = self.now, nil, nil
        end
        return
    end
    s.disagreementSince = nil
    self.current.agreement = "AGREE"
    local value = math.min(a.last, b.last)
    if s.last == nil or forceBaseline then
        local high = s.high
        if high == nil or value > high then high = value end
        s.last, s.high, s.lastAgreeAt = value, high, self.now
        s.pending = nil
        return
    end
    if value < s.last - self.options.progressEpsilon then
        s.pending, s.last, s.lastAgreeAt = nil, value, self.now
        s.coverageBreak = self.now
        return
    end
    if value > (s.high or value) + self.options.progressEpsilon then
        local p = s.pending or {from = s.high, observedAt = self.now,
            intervalStart = s.lastAgreeAt or previousAt or self.now}
        p.to, p.delta, p.intervalEnd = value, value - p.from, self.now
        if p.delta <= self.options.maxStep + self.options.progressEpsilon then
            s.pending = p
        else
            self.totals.corroborated.quarantinedDelta = self.totals.corroborated.quarantinedDelta + p.delta
            s.pending, s.coverageBreak = nil, self.now
        end
        s.high = value
    end
    s.last, s.lastAgreeAt = value, self.now
    if s.pending and math.abs(value - s.pending.to) <= self.options.progressEpsilon
        and self.now - s.pending.observedAt >= self.options.confirmSeconds then
        self:_accept("corroborated", s.pending)
        s.pending = nil
    end
